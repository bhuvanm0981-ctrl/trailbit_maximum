// Downloads the Latin subset of Trailbit's three font families from Google Fonts into frontend/fonts/,
// so the site serves its own fonts and visitors' browsers never contact Google.
// Run:  node tools/fetch-fonts.mjs
// All three families are licensed under the SIL Open Font License, which allows self-hosting.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "frontend", "fonts");
const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=Bricolage+Grotesque:opsz,wght@12..96,600;12..96,800&family=JetBrains+Mono:wght@400;500&display=swap";
// Google serves woff2 only to browsers it recognises.
const USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": USER_AGENT } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)].filter((match) => match[1] === "latin");
if (!blocks.length) throw new Error("No latin font blocks found: Google's response format changed.");

await mkdir(OUT, { recursive: true });
const rules = [];
const seen = new Set();
for (const [, , block] of blocks) {
  const family = /font-family:\s*'([^']+)'/.exec(block)[1];
  const weight = /font-weight:\s*([^;]+);/.exec(block)[1].trim().replace(/\s+/g, "-");
  const url = /url\((https:[^)]+\.woff2)\)/.exec(block)[1];
  let file = `${family.replace(/\s+/g, "")}-${weight}.woff2`;
  for (let n = 2; seen.has(file); n++) file = file.replace(/(-\d+)?\.woff2$/, `-${n}.woff2`);
  seen.add(file);
  const bytes = Buffer.from(await (await fetch(url)).arrayBuffer());
  await writeFile(join(OUT, file), bytes);
  rules.push(block.replace(/url\([^)]+\)/, `url(${file})`).replace(/\n\s*/g, " "));
  console.log(`${file}  ${(bytes.length / 1024).toFixed(1)} KB`);
}
await writeFile(join(OUT, "fonts.css"), `/* Generated by tools/fetch-fonts.mjs. Latin subset, self-hosted. */\n${rules.join("\n")}\n`);
